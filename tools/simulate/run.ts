/**
 * Circle Lab: Monte Carlo study that drives the real circle engine.
 *
 * Model: each round, each member independently misses their payment with
 * probability p (per-round default rate). Everything else (slashing, safety
 * pot, skipped turns, offsets) is executed by src/engine/circle.ts itself,
 * so the tables describe the actual rules, not a re-implementation.
 *
 * Usage: npm run simulate [-- --circles 2000]
 */
import fs from "node:fs";
import path from "node:path";
import { createCircle, defaultParams, join, start, contribute, settle, finish, currentRound } from "../../src/engine/circle";

const arg = process.argv.indexOf("--circles");
const CIRCLES = arg > 0 ? Number(process.argv[arg + 1]) : 2000;

function mulberry(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export interface Cell {
  members: number;
  p: number;
  collateralPct: number;
  reserveBps: number;
  fullPayoutRate: number; // share of circles where every payout was paid in full
  avgShortfallPct: number; // mean shortfall per payout, as % of the target pot
  recoveryPct: number; // total paid out / total target, over all payouts
}

const C = 100_000_000;

export function runCell(members: number, p: number, collateralPct: 0 | 50 | 100, reserveBps: number, circles = CIRCLES): Cell {
  let full = 0, shortSum = 0, payoutsN = 0, paid = 0, target = 0;
  for (let k = 0; k < circles; k++) {
    const r = mulberry(k * 7919 + members * 101 + Math.round(p * 1000));
    const par = defaultParams({ members, contribution: C, collateralPct, reserveBps, tipCap: 0, periodSecs: 100, graceSecs: 0 });
    const c = createCircle("s", "m0", par, k + 1);
    for (let i = 0; i < members; i++) join(c, `m${i}`, 0);
    start(c, 0);
    const targetPot = members * C - Math.floor((members * C * reserveBps) / 10_000);
    let allFull = true;
    let guard = 0;
    while (currentRound(c) && guard++ < 100) {
      const rd = currentRound(c)!;
      for (const m of c.members) if (r() >= p) contribute(c, m.id, rd.index, C, 0);
      const out = settle(c, "", rd.dueAt + 1);
      if (out.recipient) {
        payoutsN++;
        const short = Math.max(0, targetPot - out.payout);
        if (short > 0) allFull = false;
        shortSum += short / targetPot;
        paid += Math.min(out.payout, targetPot);
        target += targetPot;
      }
    }
    finish(c, 1e9);
    if (allFull) full++;
  }
  return {
    members, p, collateralPct, reserveBps,
    fullPayoutRate: full / circles,
    avgShortfallPct: payoutsN ? (shortSum / payoutsN) * 100 : 0,
    recoveryPct: target ? (paid / target) * 100 : 100,
  };
}

const sizes = [5, 10];
const ps = [0.02, 0.05, 0.1, 0.2];
const cols: (0 | 50 | 100)[] = [0, 50, 100];
const reserves = [0, 200, 500];
const cells: Cell[] = [];
for (const n of sizes) for (const p of ps) for (const c of cols) for (const rb of reserves) cells.push(runCell(n, p, c, rb));

// Recommendation: cheapest setup (least collateral, then least reserve) that pays every
// payout in full in at least 95% of simulated circles; otherwise the best fullPayoutRate.
const TARGET = 0.95;
const rec: Record<string, { collateralPct: number; reserveBps: number; fullPayoutRate: number; meetsTarget: boolean }> = {};
for (const n of sizes) for (const p of ps) {
  const sub = cells.filter((c) => c.members === n && c.p === p);
  const ok = sub.filter((c) => c.fullPayoutRate >= TARGET).sort((a, b) => a.collateralPct - b.collateralPct || a.reserveBps - b.reserveBps);
  const best = ok[0] ?? [...sub].sort((a, b) => b.fullPayoutRate - a.fullPayoutRate || a.collateralPct - b.collateralPct)[0];
  rec[`${n}:${p}`] = { collateralPct: best.collateralPct, reserveBps: best.reserveBps, fullPayoutRate: best.fullPayoutRate, meetsTarget: ok.length > 0 };
}

const out = { generatedWith: { circlesPerCell: CIRCLES, target: TARGET, engine: "src/engine/circle.ts" }, cells, recommendations: rec };
fs.mkdirSync(path.resolve("src/data"), { recursive: true });
fs.writeFileSync(path.resolve("src/data/circle-lab.json"), JSON.stringify(out, null, 1));

const pct = (x: number) => (x * 100).toFixed(1) + "%";
let md = `# Circle Lab results\n\nGenerated by \`npm run simulate\` (${CIRCLES} circles per cell, seeded, reproducible). The simulator drives the real engine in \`src/engine/circle.ts\`.\n\n` +
  `**Model.** Each round every member independently misses their payment with probability *p*. "Full payout" means the recipient received the whole pot (net of the safety-pot share). "Recovery" is total paid out divided by total target over all payouts. ` +
  `Defaults are independent; real groups have correlated defaults (a shared bad month), so treat these as optimistic bounds.\n\n`;
for (const n of sizes) {
  md += `## ${n} members\n\n| Per-round default rate | Collateral | Safety pot | Circles fully paid | Avg shortfall | Recovery |\n|---|---|---|---|---|---|\n`;
  for (const c of cells.filter((x) => x.members === n))
    md += `| ${(c.p * 100).toFixed(0)}% | ${c.collateralPct}% | ${(c.reserveBps / 100).toFixed(0)}% | ${pct(c.fullPayoutRate)} | ${c.avgShortfallPct.toFixed(2)}% | ${c.recoveryPct.toFixed(2)}% |\n`;
  md += "\n";
}
md += `## Recommended settings (target: at least ${TARGET * 100}% of circles fully paid)\n\n| Members | Default rate | Collateral | Safety pot | Fully paid | Meets target |\n|---|---|---|---|---|---|\n`;
for (const [k, v] of Object.entries(rec)) {
  const [n, p] = k.split(":");
  md += `| ${n} | ${(Number(p) * 100).toFixed(0)}% | ${v.collateralPct}% | ${(v.reserveBps / 100).toFixed(0)}% | ${pct(v.fullPayoutRate)} | ${v.meetsTarget ? "yes" : "no"} |\n`;
}
fs.writeFileSync(path.resolve("docs/CIRCLE_LAB.md"), md);
console.log(md.split("## Recommended")[1] ? "## Recommended" + md.split("## Recommended")[1] : "done");
